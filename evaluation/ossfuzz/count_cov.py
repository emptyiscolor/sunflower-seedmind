#!/usr/bin/env python3

"""
Script to count the number of coverage files generated by OSS-Fuzz.


"""
import sys
import csv
import os
import subprocess
import json


def main():
    if len(sys.argv) != 4:
        print("Usage: python3 count_cov.py <csv_file> <corpus_dir> <output_csv>")
        sys.exit(1)

    csv_file = sys.argv[1]
    corpus_dir = sys.argv[2]
    output_csv = sys.argv[3]
    cov = {}

    with open(csv_file, 'r') as f:
        reader = csv.reader(f)
        rows = list(reader)

    for row in rows:
        if len(row) < 2:
            continue
        project, harness = row[0], row[1]
        key = (project, harness)

        # Initialize coverage to 0
        cov[key] = 0

        # Check if corpus directory exists
        project_corpus = os.path.join(corpus_dir, project)
        if not os.path.isdir(project_corpus):
            continue

        # Run coverage command
        cmd = [
            "python3", "infra/helper.py", "coverage", project,
            "--no-serve",
            f"--fuzz-target={harness}",
            f"--corpus-dir={project_corpus}"
        ]

        try:
            # Timeout 30m
            subprocess.run(cmd, timeout=1800)
        except subprocess.TimeoutExpired:
            # Stop all containers on timeout
            subprocess.run("docker stop $(docker ps -q)", shell=True)

        # Parse coverage report
        report_file = f"./build/out/{project}/report/linux/summary.json"
        if os.path.exists(report_file):
            try:
                with open(report_file) as rf:
                    data = json.load(rf)
                    # Equivalent to: jq .data[].totals.lines.percent
                    for item in data.get("data", []):
                        percent = item.get("totals", {}).get(
                            "lines", {}).get("percent", 0)
                        if percent > cov[key]:
                            cov[key] = percent
            except Exception as e:
                print(f"Error processing report for {project}: {e}")

    with open(output_csv, 'w') as f:
        writer = csv.writer(f)
        for row in rows:
            if len(row) < 2:
                continue
            project, harness = row[0], row[1]
            writer.writerow([harness, cov.get((project, harness), 0)])


if __name__ == "__main__":
    main()
